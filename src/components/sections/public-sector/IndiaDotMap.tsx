// 4 cohesive blue state tints
const TINTS = [
  "#BFDBFE", // light blue
  "#93C5FD", // soft blue
  "#3B82F6", // primary blue
  "#1D4ED8", // deep blue
];

const IndiaDotMap = memo(function IndiaDotMap() {
  return (
    <svg
      viewBox="-4 -4 310 338"
      fill="none"
      aria-hidden
      className="h-auto w-full max-w-[220px] sm:max-w-[240px]"
    >
      {DOTS.map(([x, y, tone, pulse], idx) => (
        <rect
          key={idx}
          x={x * PITCH}
          y={y * PITCH}
          width={CELL}
          height={CELL}
          rx="2"
          fill={TINTS[tone]}
          opacity={tone === 0 ? 0.6 : tone === 1 ? 0.8 : tone === 2 ? 0.9 : 1}
        >
          {pulse === 1 && (
            <animate
              attributeName="opacity"
              values="1;0.25;1"
              dur="3s"
              begin={`${((x + y) % 7) * 0.4}s`}
              repeatCount="indefinite"
            />
          )}
        </rect>
      ))}
    </svg>
  );
});

export default IndiaDotMap;